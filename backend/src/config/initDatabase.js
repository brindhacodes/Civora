const pool = require('./database');

const schema = `
    CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        email TEXT NOT NULL UNIQUE,
        password_hash TEXT NOT NULL,
        latitude DOUBLE PRECISION CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
        longitude DOUBLE PRECISION CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
        role TEXT NOT NULL DEFAULT 'citizen' CHECK (role IN ('citizen', 'admin')),
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS complaints (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        complaint_id TEXT NOT NULL UNIQUE,
        name TEXT NOT NULL,
        phone TEXT NOT NULL,
        email TEXT,
        area TEXT NOT NULL,
        city TEXT NOT NULL,
        landmark TEXT,
        issue_type TEXT NOT NULL,
        description TEXT NOT NULL,
        severity TEXT NOT NULL DEFAULT 'medium' CHECK (severity IN ('low', 'medium', 'high')),
        duration TEXT,
        allow_volunteers TEXT NOT NULL DEFAULT 'no' CHECK (allow_volunteers IN ('yes', 'no')),
        want_updates TEXT NOT NULL DEFAULT 'no' CHECK (want_updates IN ('yes', 'no')),
        image_url TEXT,
        latitude DOUBLE PRECISION CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
        longitude DOUBLE PRECISION CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
        status TEXT NOT NULL DEFAULT 'Submitted' CHECK (status IN ('Pending', 'Submitted', 'Assigned', 'In Progress', 'Resolved')),
        department TEXT NOT NULL DEFAULT 'General Administration',
        remarks TEXT,
        resolution_proof_url TEXT,
        assigned_at TIMESTAMPTZ,
        resolved_at TIMESTAMPTZ,
        supporter_count INTEGER NOT NULL DEFAULT 1 CHECK (supporter_count >= 0),
        user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS comments (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        complaint_id TEXT NOT NULL REFERENCES complaints(complaint_id) ON DELETE CASCADE,
        author_name TEXT NOT NULL,
        message TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS complaint_joins (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        complaint_id BIGINT NOT NULL REFERENCES complaints(id) ON DELETE CASCADE,
        user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
        session_id TEXT,
        joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE INDEX IF NOT EXISTS complaints_status_idx ON complaints(status);
    CREATE INDEX IF NOT EXISTS complaints_department_idx ON complaints(department);
    CREATE INDEX IF NOT EXISTS complaints_user_id_idx ON complaints(user_id);
    CREATE INDEX IF NOT EXISTS complaints_created_at_idx ON complaints(created_at DESC);
    CREATE INDEX IF NOT EXISTS complaints_location_idx ON complaints(latitude, longitude)
        WHERE latitude IS NOT NULL AND longitude IS NOT NULL;
    CREATE INDEX IF NOT EXISTS comments_complaint_id_idx ON comments(complaint_id);
    CREATE INDEX IF NOT EXISTS complaint_joins_complaint_id_idx ON complaint_joins(complaint_id);
    CREATE INDEX IF NOT EXISTS complaint_joins_user_id_idx ON complaint_joins(user_id);
`;

const initDatabase = async () => {
    await pool.query(schema);
    console.log('PostgreSQL schema and indexes are ready');
};

if (require.main === module) {
    initDatabase()
        .then(async () => {
            await pool.end();
            console.log('Database initialization complete');
        })
        .catch(async (error) => {
            console.error('Database initialization failed:', error);
            await pool.end().catch(() => {});
            process.exitCode = 1;
        });
}

module.exports = initDatabase;
